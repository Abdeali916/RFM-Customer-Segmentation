-- Find the number of customers in each RFM segment

SELECT
    Customer_Segment,
    COUNT(*) AS Customer_Count
FROM Customer_RFM_Final
GROUP BY Customer_Segment
ORDER BY Customer_Count DESC;
---Insight:The largest segment is Lost Customers (912), followed closely by Most Loyal Customers (905) and Loyal Customers (892).



-- Find total revenue and average customer revenue for each RFM segment

SELECT
    Customer_Segment,
    COUNT(*) AS Customer_Count,
    SUM(Monetary) AS Total_Revenue,
    AVG(Monetary) AS Average_Revenue_Per_Customer
FROM Customer_RFM_Final
GROUP BY Customer_Segment
ORDER BY Total_Revenue DESC;
--Insight:Most Loyal Customers generate the highest total revenue at approximately €5.66 million


-- Compare average customer revenue across RFM segments

SELECT
    Customer_Segment,
    AVG(Monetary) AS Average_Revenue_Per_Customer
FROM Customer_RFM_Final
GROUP BY Customer_Segment
ORDER BY Average_Revenue_Per_Customer DESC;
--Insight:Most Loyal Customers generate the highest average revenue per customer (€6,256).

