-- Calculate revenue generated by At Risk customers

SELECT
    SUM(Monetary) AS At_Risk_Revenue,
    COUNT(*) AS At_Risk_Customers
FROM Customer_RFM_Final
WHERE Customer_Segment = 'At Risk';
--Insight:At-Risk customers (418) generate approximately €732,823 in revenue, making them an important retention opportunity.

-- Calculate each customer segment's contribution to total revenue

SELECT
    Customer_Segment,
    SUM(Monetary) AS Segment_Revenue,
    ROUND(
        SUM(Monetary) * 100.0 / (SELECT SUM(Monetary) FROM Customer_RFM_Final),
        2
    ) AS Revenue_Percentage
FROM Customer_RFM_Final
GROUP BY Customer_Segment
ORDER BY Revenue_Percentage DESC;
--Insight:Most Loyal Customers contribute the largest share of revenue at 63.71%.

-- Calculate the number and percentage of inactive or at-risk customers

SELECT
    COUNT(*) AS At_Risk_Or_Lost_Customers,
    ROUND(
        COUNT(*) * 100.0 / (SELECT COUNT(*) FROM Customer_RFM_Final),
        2
    ) AS Customer_Percentage
FROM Customer_RFM_Final
WHERE Customer_Segment IN ('At Risk', 'Lost Customers');
--Insight:1,330 customers (30.66%) are either At Risk or Lost, indicating a significant customer-retention challenge.

-- Find the top 10 countries by total revenue

SELECT TOP 10
    Country,
    SUM(Revenue) AS Total_Revenue,
    COUNT(DISTINCT CustomerID) AS Customer_Count
FROM OnlineRetail
GROUP BY Country
ORDER BY Total_Revenue DESC;
--Insight:The United Kingdom is the dominant market, generating approximately €7.29 million in revenue.

-- Find the top 10 products by total revenue

SELECT TOP 10
    StockCode,
    Description,
    SUM(Revenue) AS Total_Revenue,
    SUM(Quantity) AS Total_Quantity
FROM OnlineRetail
GROUP BY StockCode, Description
ORDER BY Total_Revenue DESC;
--Insight:PAPER CRAFT, LITTLE BIRDIE is the highest-revenue product, generating approximately €168,470.

-- Find monthly revenue to identify the highest-performing months

SELECT
    YEAR(InvoiceDate) AS Sales_Year,
    MONTH(InvoiceDate) AS Sales_Month,
    SUM(Revenue) AS Total_Revenue
FROM OnlineRetail
GROUP BY
    YEAR(InvoiceDate),
    MONTH(InvoiceDate)
ORDER BY Total_Revenue DESC;
--Insight:November 2011 was the highest-revenue month, generating approximately €1.16 million

-- Compare average purchase frequency across RFM segments

